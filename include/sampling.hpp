/**
 * \brief A sampler that cycles through a number of points in a cache
 */
struct CachedSampler : Sampler
{
    std::shared_ptr<Sampler> sampler;
    std::vector<Vector> cache;
    size_t index;
    size_t n_samples;

    CachedSampler(const std::shared_ptr<Sampler> sampler) :
        Sampler(sampler->d),
        sampler(sampler),
        cache(),
        index(0),
        n_samples(std::max(constants::cache_min_samples,
                           utils::nearest_power_of_2(constants::cache_max_doubles / sampler->d)))
    {
        cache.reserve(n_samples);
    }

    CachedSampler(const std::vector<Vector> &cache, const bool transform_ppf = false) :
        Sampler(cache[0].size()),
        sampler(std::make_shared<Tester>(cache[0].size())),
        cache(cache),
        index(cache.size()),
        n_samples(cache.size())
    {
        if (transform_ppf)
            for (auto &sample : this->cache)
                for (auto &si : sample)
                    si = ppf(si);
    }

    void sample(Eigen::Ref<Vector> out) override
    {
        // The first n_samples samples fill the cache (allocating); later ones only copy
        if (index < n_samples)
            cache.emplace_back((*sampler)());

        out = cache[index++ % n_samples];
    }
};

/***
 * \brief Abstract class for sample transformation methods
 */
struct SampleTransformer : Sampler
{

    SampleTransformer(const std::shared_ptr<Sampler> sampler) :
        Sampler(sampler->d),
        sampler(sampler)
    {
    }

    /**
     * Should be overwritten: transforms U(0,1) independent samples into something else, in
     * place
     */
    virtual void transform_inplace(Eigen::Ref<Vector> x) = 0;

    //! The transformation of x, as a new vector
    [[nodiscard]] Vector transform(const Vector &x)
    {
        Vector y = x;
        transform_inplace(y);
        return y;
    }

    void sample(Eigen::Ref<Vector> out) override
    {
        sampler->sample(out);
        transform_inplace(out);
    }

    void reset(const parameters::Modules &m, const size_t l) override { sampler->reset(m, l); }

    [[nodiscard]] Vector raw() { return (*sampler)(); }

    std::shared_ptr<Sampler> sampler;
};

struct IdentityTransformer : SampleTransformer
{
    IdentityTransformer(const std::shared_ptr<Sampler> sampler) :
        SampleTransformer(sampler)
    {
    }

    void transform_inplace(Eigen::Ref<Vector>) override {}
};

//! Adds ppf to transform into gaussian
struct GaussianTransformer : SampleTransformer
{
    GaussianTransformer(const std::shared_ptr<Sampler> sampler) :
        SampleTransformer(sampler)
    {
    }

    Float expected_length() override
    {
        const Float dd = static_cast<Float>(this->sampler->d);
        return sqrt(dd) * (1.0 - 1.0 / (4.0 * dd) + 1.0 / (21.0 * pow(dd, 2.0)));
    }

    [[nodiscard]] inline std::pair<Float, Float> box_muller(const Float u1, const Float u2)
    {
        const Float r = std::sqrt(-2.0 * std::log(u1));
        const Float theta = 2.0 * M_PI * u2;
        return {r * std::cos(theta), r * std::sin(theta)};
    }

    // State of the Box-Muller transform for odd dimensions, per transformer object (these used to
    // be function statics shared by all objects and threads).
    Vector u_extra;
    Eigen::Index n_extra_used = 0;
    bool needs_new_sample = true;
    Float extra_sample = 0;

    //! Box-Muller in place: pairs (u_2i, u_2i+1) become two standard normal numbers
    inline void box_muller_inplace(Eigen::Ref<Vector> u)
    {
        const Eigen::Index n = u.size();
        const Eigen::Index m = n / 2;

        for (Eigen::Index i = 0; i < m; ++i)
        {
            const auto [n1, n2] = box_muller(u(2 * i), u(2 * i + 1));
            u(2 * i) = n1;
            u(2 * i + 1) = n2;
        }

        if (n % 2 != 0)
        {
            if (u_extra.size() <= n_extra_used)
            {
                u_extra.resize(static_cast<Eigen::Index>(sampler->d));
                sampler->sample(u_extra);
                n_extra_used = 0;
            }

            if (needs_new_sample)
            {
                const auto [n1, n2] = box_muller(u(n - 1), u_extra(n_extra_used++));
                u(n - 1) = n1;
                extra_sample = n2;
                needs_new_sample = false;
            }
            else
            {
                u(n - 1) = extra_sample;
                needs_new_sample = true;
            }
        }
    }

    void transform_inplace(Eigen::Ref<Vector> x) override
    {
        if (constants::use_box_muller)
            box_muller_inplace(x);
        else
            x = x.unaryExpr(&ppf);
    }
};

struct UniformScaler : SampleTransformer
{
    static inline Float scale = std::sqrt(3.0);

    UniformScaler(const std::shared_ptr<Sampler> sampler) :
        SampleTransformer(sampler)
    {
    }

    void transform_inplace(Eigen::Ref<Vector> x) override
    {
        x = (-scale + (2.0 * scale) * x.array()).matrix();
    }
};

struct LaplaceTransformer : SampleTransformer
{
    static inline Float b = std::sqrt(0.5);

    LaplaceTransformer(const std::shared_ptr<Sampler> sampler) :
        SampleTransformer(sampler)
    {
    }

    void transform_inplace(Eigen::Ref<Vector> x) override
    {
        x = ((x.array() < 0.5)
                 .select(b * (2.0 * x.array()).log(), -b * (2.0 * (1.0 - x.array())).log()))
                .matrix();
    }
};

struct LogisticTransformer : SampleTransformer
{
    static inline Float s = std::sqrt(3.0) / M_PI;

    LogisticTransformer(const std::shared_ptr<Sampler> sampler) :
        SampleTransformer(sampler)
    {
    }

    void transform_inplace(Eigen::Ref<Vector> x) override
    {
        // Evaluated into an aligned vector: Eigen's vectorized log (plog) and std::log differ in
        // the last bit, and an unaligned destination (a column of the population) would compute
        // its first coefficients with std::log, changing the samples' bits.
        scratch = (s * (x.array() / (1.0 - x.array())).log()).matrix();
        x = scratch;
    }

  private:
    Vector scratch;
};

struct CauchyTransformer : SampleTransformer
{
    static inline Float gamma = 1.0;

    CauchyTransformer(const std::shared_ptr<Sampler> sampler) :
        SampleTransformer(sampler)
    {
    }

    Float expected_length() override
    {
        // TODO: this should be something like 1.18 * n
        // Expectation is undef, we can use median?
        const Float dd = static_cast<Float>(this->sampler->d);
        // Empirically approximated median
        const Float median_z = dd * (1.0 + 0.18 * std::tanh(dd / 4.07));
        return median_z;
    }

    void transform_inplace(Eigen::Ref<Vector> x) override
    {
        x = (gamma * (M_PI * (x.array() - 0.5)).tan()).matrix();
    }
};

struct DoubleWeibullTransformer : SampleTransformer
{
    DoubleWeibullTransformer(const std::shared_ptr<Sampler> sampler) :
        SampleTransformer(sampler)
    {
    }

    void transform_inplace(Eigen::Ref<Vector> x) override
    {
        x = ((x.array() < 0.5)
                 .select(-(-((2.0 * x.array()).log())).sqrt(),
                         (-((2.0 * (1.0 - x.array())).log())).sqrt()))
                .matrix();
    }
};

