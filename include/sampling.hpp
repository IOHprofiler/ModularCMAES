/**
 * @brief Sampler generic class: generates vectors of random numbers of size d.
 *
 * Subclasses implement sample(out), which writes one sample into out (a vector or a column of a
 * matrix, without allocating). operator()() returns a new vector, for code that wants one.
 */
struct Sampler
{
    Sampler(const size_t d) :
        d(d)
    {
    }
    virtual ~Sampler() = default;

    size_t d;

    virtual void reset(const parameters::Modules &, const size_t) {}

    //! A generation starts: Orthogonal starts a new block (#76), Mirrored a new pair. The
    //! optimizer calls it at the start of every population; most samplers do nothing.
    virtual void begin_generation() {}

    virtual Float expected_length() { return std::sqrt(static_cast<Float>(d)); }

    //! Write one sample into out (out.size() == d)
    virtual void sample(Eigen::Ref<Vector> out) = 0;

    //! One sample as a new vector
    [[nodiscard]] Vector operator()()
    {
        Vector x(d);
        sample(x);
        return x;
    }
};

/**
 * @brief Testing sampler, simple incrementing generator.
 */
struct Tester : Sampler
{
    Tester(const size_t d) :
        Sampler(d)
    {
    }

    void sample(Eigen::Ref<Vector> out) override;

  private:
    size_t i = 0;
};

/**
 * @brief Random sampling functor
 * @tparam Distribution a random number generator from std::random
 */
template <typename Distribution = rng::normal<Float>> struct Random : Sampler
{

    Random(const size_t d, std::shared_ptr<rng::Generator> generator = rng::global()) :
        Sampler(d),
        dist{},
        generator(std::move(generator))
    {
    }
    Random(const size_t d,
           const Distribution &dist,
           std::shared_ptr<rng::Generator> generator = rng::global()) :
        Sampler(d),
        dist(dist),
        generator(std::move(generator))
    {
    }

    void sample(Eigen::Ref<Vector> out) override
    {
        rng::Generator &gen = *generator;
        for (auto &xi : out)
            xi = dist(gen);
    }

  private:
    Distribution dist;
    std::shared_ptr<rng::Generator> generator;
};

