/**
 * @brief Mirrored sampler, returns the original sample generated by
 * the provided sampler, followed by its reversed form.
 *
 * A standalone sampler: the optimizer does not use it. Modules::mirrored is applied by
 * mutation::Strategy, which samples the pairs of each generation together (#75).
 */
struct Mirrored : Sampler
{
    Mirrored(const std::shared_ptr<Sampler> sampler) :
        Sampler(sampler->d),
        sampler(sampler),
        previous(sampler->d)
    {
    }

    void sample(Eigen::Ref<Vector> out) override;

    void reset(const parameters::Modules &m, const size_t l) override
    {
        sampler->reset(m, l);
        mirror = false;
    }

    void begin_generation() override
    {
        sampler->begin_generation();
        mirror = false;
    }

    //! A mirrored sample has the length of the sample it mirrors
    Float expected_length() override { return sampler->expected_length(); }

  private:
    std::shared_ptr<Sampler> sampler;
    Vector previous;
    bool mirror = false;
};

/**
 * @brief Orthogonal sampler (Wang et al. 2014; Wang, Emmerich and Baeck 2019, Sec. 3.2).
 *
 * The samples of a generation, n_samples of them, are orthogonalized in blocks: the first
 * min(n_samples, d), then further blocks of at most d (more than d vectors cannot be orthogonal).
 * Each block is drawn from the wrapped sampler when it is needed, orthonormalized as the
 * Gram-Schmidt process does (a Householder QR decomposition with the signs of Q corrected so that
 * diag(R) > 0, Mezzadri 2007), and every vector gets the length of the sample it came from.
 * begin_generation() starts the next generation with a new block (#76, F11); without it, every
 * n_samples consecutive samples are a generation. Samples drawn to replace rejected ones (bound
 * correction RESAMPLE, repelling) count towards the generation.
 *
 * Wang et al. (2019, Alg. 4) draw the samples beyond the first d at random; here they are
 * orthogonalized in further blocks of d.
 */
struct Orthogonal : Sampler
{
    Orthogonal(const std::shared_ptr<Sampler> sampler, const size_t n_samples) :
        Sampler(sampler->d),
        sampler(sampler),
        n(std::max<size_t>(1, n_samples)),
        qr(d, d),
        samples(d, d),
        lengths(d)
    {
    }

    void sample(Eigen::Ref<Vector> out) override;

    void reset(const parameters::Modules &mod, const size_t lambda) override;

    void begin_generation() override;

    //! The number of independent samples in a generation of lambda individuals: lambda, or
    //! ceil(lambda / 2) with mirrored sampling (the second of each pair is the negation of the
    //! first)
    static size_t get_n_samples(const parameters::Modules &modules, const size_t lambda);

    //! The samples keep the lengths of the samples of the wrapped sampler
    Float expected_length() override { return sampler->expected_length(); }

  private:
    std::shared_ptr<Sampler> sampler;
    //! The number of samples of a generation
    size_t n;
    //! The samples of the generation that are not yet in a block
    size_t remaining = 0;
    //! The size of the current block, and the next of its samples to return
    Eigen::Index block_size = 0;
    Eigen::Index current = 0;
    Eigen::HouseholderQR<Matrix> qr;
    Matrix samples;
    Vector lengths;
    Vector workspace;

    //! Draw and orthogonalize the next block
    void next_block();
};

